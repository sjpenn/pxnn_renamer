from datetime import datetime, timedelta

from backend.app.core.config import settings
from backend.app.core.security import create_access_token
from backend.app.database.models import CouponCode, User
from backend.app.services.coupons import create_coupon


def _make_user(db, username, is_admin=False, credits=0):
    user = User(
        username=username,
        email=f"{username}@example.com",
        password_hash="x",
        is_admin=is_admin,
        credit_balance=credits,
    )
    db.add(user)
    db.commit()
    db.refresh(user)
    return user


def _login(client, user):
    token = create_access_token(str(user.id))
    client.cookies.set(settings.COOKIE_NAME, token)


def test_redeem_valid_coupon_grants_credits(client, db):
    user = _make_user(db, "redeemer")
    create_coupon(db, credits=7, code="LAUNCH7")
    db.commit()
    _login(client, user)

    response = client.post("/api/credits/redeem", data={"code": "launch7"})
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["credits_granted"] == 7
    assert body["credit_balance"] == 7


def test_redeem_same_coupon_twice_fails(client, db):
    user = _make_user(db, "doubledip")
    create_coupon(db, credits=3, code="ONCE")
    db.commit()
    _login(client, user)

    assert client.post("/api/credits/redeem", data={"code": "ONCE"}).status_code == 200
    response = client.post("/api/credits/redeem", data={"code": "ONCE"})
    assert response.status_code == 400
    assert "already redeemed" in response.json()["detail"]


