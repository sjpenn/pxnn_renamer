def test_redeem_inactive_and_unknown_codes_fail(client, db):
    user = _make_user(db, "hopeful")
    coupon = create_coupon(db, credits=3, code="PAUSED")
    coupon.is_active = False
    db.commit()
    _login(client, user)

    assert client.post("/api/credits/redeem", data={"code": "PAUSED"}).status_code == 400
    assert client.post("/api/credits/redeem", data={"code": "NEVEREXISTED"}).status_code == 400


def test_redeem_respects_max_redemptions(client, db):
    create_coupon(db, credits=2, code="LIMIT1", max_redemptions=1)
    db.commit()

    first = _make_user(db, "firstuser")
    _login(client, first)
    assert client.post("/api/credits/redeem", data={"code": "LIMIT1"}).status_code == 200

    second = _make_user(db, "seconduser")
    _login(client, second)
    response = client.post("/api/credits/redeem", data={"code": "LIMIT1"})
    assert response.status_code == 400
    assert "redemption limit" in response.json()["detail"]


