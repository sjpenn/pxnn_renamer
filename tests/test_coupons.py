def test_founder_creates_coupon_with_autogenerated_code(client, db):
    admin = _make_user(db, "founder2", is_admin=True)
    _login(client, admin)

    response = client.post(
        "/admin/founder/coupons",
        data={"credits": "10", "code": "", "max_redemptions": "5", "expires_on": "", "note": "test"},
        follow_redirects=False,
    )
    assert response.status_code == 303
    coupon = db.query(CouponCode).first()
    assert coupon is not None
    assert coupon.credits == 10
    assert coupon.max_redemptions == 5
    assert coupon.code.startswith("PXNN-")


def test_founder_grants_credits_by_username(client, db):
    admin = _make_user(db, "founder3", is_admin=True)
    target = _make_user(db, "luckyfan", credits=1)
    _login(client, admin)

    response = client.post(
        "/admin/founder/credits",
        data={"username": "luckyfan", "amount": "9"},
        follow_redirects=False,
    )
    assert response.status_code == 303
    db.refresh(target)
    assert target.credit_balance == 10


def test_founder_toggle_and_delete_coupon(client, db):
    admin = _make_user(db, "founder4", is_admin=True)
    coupon = create_coupon(db, credits=2, code="TOGGLEME")
    db.commit()
    _login(client, admin)

    client.post(f"/admin/founder/coupons/{coupon.id}/toggle", follow_redirects=False)
    db.refresh(coupon)
    assert coupon.is_active is False

    client.post(f"/admin/founder/coupons/{coupon.id}/delete", follow_redirects=False)
    assert db.query(CouponCode).filter(CouponCode.id == coupon.id).first() is None


def test_founder_updates_platform_settings(client, db):
    admin = _make_user(db, "founder5", is_admin=True)
    _login(client, admin)

    response = client.post(
        "/admin/founder/settings",
        data={
            "trial_credits": "3",
            "max_upload_files": "50",
            "max_upload_file_mb": "100",
            "max_upload_batch_mb": "500",
            "allowed_upload_extensions": "mp3, wav, .FLAC",
        },
        follow_redirects=False,
    )
    assert response.status_code == 303

    from backend.app.services.site_settings import get_setting

    assert get_setting(db, "trial_credits", "") == "3"
    assert get_setting(db, "max_upload_files", "") == "50"
    assert get_setting(db, "allowed_upload_extensions", "") == "mp3,wav,flac"
